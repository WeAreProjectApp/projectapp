def split_projects(apps, schema_editor):
    Connector = apps.get_model('content', 'McpConnector')
    Credential = apps.get_model('content', 'McpCredential')
    alias = schema_editor.connection.alias
    Connector.objects.using(alias).get_or_create(slug='data-integrity', defaults={
        'name': 'Integridad de datos', 'description': 'Revisión transversal y correcciones auditadas con vista previa y deshacer.',
        'is_active': False,
    })
    connector = Connector.objects.using(alias).filter(slug='projects').first()
    if connector:
        Connector.objects.using(alias).filter(pk=connector.pk).update(
            pre_split_started_at=timezone.now(), pre_split_consumers_verified_at=None)
        for credential in Credential.objects.using(alias).filter(connector=connector, catalog='canonical'):
            credential.catalog = 'pre_split'
            credential.allowed_tools = credential.allowed_tools or PRE_SPLIT_NAMES
            credential.migrated_at = None
            credential.save(using=alias, update_fields=['catalog', 'allowed_tools', 'migrated_at'])


